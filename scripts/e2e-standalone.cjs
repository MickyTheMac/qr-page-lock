const { chromium } = require("playwright");
const { spawn } = require("node:child_process");
const path = require("node:path");
const fx = (f) => path.join(__dirname, "..", "fixtures", f);
(async () => {
  const dir = process.argv[2];
  const server = spawn("python3", ["-m", "http.server", "4174", "-d", dir], { stdio: "ignore" });
  await new Promise((r) => setTimeout(r, 800));
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 420, height: 900 } });
  const errs = [];
  p.on("pageerror", (e) => errs.push(e.message));
  await p.goto("http://localhost:4174/#create");
  await p.setInputFiles('input[type="file"]', fx("00-original-unsealed.pdf"));
  await p.getByRole("button", { name: "Seal every page" }).click();
  await p.getByText("self-check: REFERENCE MATCH").waitFor({ timeout: 30000 });
  await p.getByText(/QR scan test/).nth(2).waitFor({ timeout: 30000 });
  console.log("scan ok:", await p.getByText("QR scan test: readable").count());
  await p.screenshot({ path: path.join(dir, "create-phone.png"), fullPage: true });
  await p.goto("http://localhost:4174/#verify");
  const inputs = p.locator('input[type="file"]');
  await inputs.nth(0).setInputFiles(fx("02-changed-character.pdf"));
  await inputs.nth(1).setInputFiles(fx("01-sealed-genuine.pagelock-reference.json"));
  await p.getByRole("button", { name: "Check every page" }).click();
  console.log("verify:", await p.locator('[data-testid="outcome"] div').first().textContent());
  const sw = await p.evaluate(() => document.documentElement.scrollWidth);
  console.log("scrollWidth", sw, "errors", errs);
  await b.close(); server.kill();
})();
